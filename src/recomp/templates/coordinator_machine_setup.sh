#!/usr/bin/env bash
# coordinator-machine-setup.sh — prepare a Linux coordinator host for recomp.
#
# Installs the host prerequisites the coordinator needs and pins the Firecracker
# verification guest by content hash:
#   * e2fsprogs, openssl, git, curl            (doctor probes these)
#   * kvm group membership for your account    (the service opens /dev/kvm)
#   * firecracker + jailer + guest kernel      (~/.local/share/recomp/firecracker)
# Run as your normal account; it uses sudo for the three system changes and is
# idempotent: existing artifacts with the right digest are left alone.
#
# Generated by `recomp coordinator machine-setup`. Do not edit pins by hand.
set -Eeuo pipefail

FIRECRACKER_VERSION="1.10.1"
FIRECRACKER_TGZ_URL="https://github.com/firecracker-microvm/firecracker/releases/download/v1.10.1/firecracker-v1.10.1-x86_64.tgz"
FIRECRACKER_TGZ_SHA256="36112969952b0e34fadcfca769d48a55dc22cbba99af17e02bd0e24fc35adc77"
FIRECRACKER_SHA256="96d25e000e5fcbf5b11dca0e1275b5d7dc0922ff8b8206aeaed98e515a8468dc"
JAILER_SHA256="8965e9ee855537561ac3adaf0b086a3882456fdc55472691f3bbe489199014ce"
KERNEL_URL="https://s3.amazonaws.com/spec.ccfc.min/firecracker-ci/v1.10/x86_64/vmlinux-6.1.102"
KERNEL_SHA256="49ba99a5299444ac59dda2efc3569cc2d58a5d72ea6475a6bfc37aa0bf322e54"
ASSET_DIR="${HOME}/.local/share/recomp/firecracker"

fail() { echo "machine-setup: $*" >&2; exit 1; }
note() { echo "machine-setup: $*"; }

[[ "$(uname -s)" == "Linux" ]] || fail "Firecracker, jailer and KVM are Linux-only"
[[ "$(uname -m)" == "x86_64" ]] || fail "this recipe pins x86_64 artifacts; adapt the pins for $(uname -m)"
[[ "$(id -u)" != 0 ]] || fail "run as your normal account (the script uses sudo where needed)"
sudo_path="$(command -v sudo || true)"
[[ -n "$sudo_path" ]] || fail "sudo is required for the system-level steps"

# /dev/null must be the null character device; a regular file there breaks every
# process that redirects to it, including the coordinator's version probes.
if [[ ! -c /dev/null ]]; then
    note "repairing /dev/null (not a character device)"
    sudo rm -f /dev/null
    sudo mknod /dev/null c 1 3
    sudo chmod 666 /dev/null
fi

missing_pkgs=()
for pkg in e2fsprogs openssl git curl ca-certificates; do
    dpkg -s "$pkg" >/dev/null 2>&1 || missing_pkgs+=("$pkg")
done
if (( ${#missing_pkgs[@]} > 0 )); then
    note "installing packages: ${missing_pkgs[*]}"
    sudo apt-get update -qq
    sudo apt-get install -y -qq "${missing_pkgs[@]}"
else
    note "packages already present (e2fsprogs, openssl, git, curl, ca-certificates)"
fi

if ! id -nG | grep -qw kvm; then
    note "adding $(id -un) to the kvm group (takes effect in new logins and service starts)"
    sudo usermod -aG kvm "$(id -un)"
else
    note "$(id -un) is already in the kvm group"
fi

sha256_of() { sha256sum "$1" | cut -d' ' -f1; }

fetch_verified() { # url destination expected_sha256
    local url="$1" destination="$2" expected="$3" part
    if [[ -f "$destination" ]] && [[ "$(sha256_of "$destination")" == "$expected" ]]; then
        note "pinned artifact present: $(basename "$destination")"
        return 0
    fi
    note "downloading $(basename "$destination")"
    part="$(mktemp)"
    curl -fsSL --retry 3 -o "$part" "$url"
    [[ "$(sha256_of "$part")" == "$expected" ]] \
        || fail "digest mismatch for $(basename "$destination"): got $(sha256_of "$part"), pinned $expected"
    mv "$part" "$destination"
    chmod 644 "$destination"
}

note "pinning the verification guest in $ASSET_DIR"
mkdir -p "$ASSET_DIR"

tgz="$(mktemp)"
fetch_verified "$FIRECRACKER_TGZ_URL" "$tgz" "$FIRECRACKER_TGZ_SHA256"
stage="$(mktemp -d)"
tar -xzf "$tgz" -C "$stage"
rm -f "$tgz"
inner="release-v${FIRECRACKER_VERSION}-x86_64"
for tool in firecracker jailer; do
    expected_var="${tool^^}_SHA256"
    expected="${!expected_var}"
    mv "$stage/$inner/$tool-v${FIRECRACKER_VERSION}-x86_64" "$ASSET_DIR/$tool.new"
    [[ "$(sha256_of "$ASSET_DIR/$tool.new")" == "$expected" ]] \
        || fail "upstream $tool digest does not match the pin: expected $expected"
    chmod 755 "$ASSET_DIR/$tool.new"
    mv "$ASSET_DIR/$tool.new" "$ASSET_DIR/$tool"
    note "pinned $tool at $expected"
done
rm -rf "$stage"

fetch_verified "$KERNEL_URL" "$ASSET_DIR/vmlinux-6.1.102" "$KERNEL_SHA256"

"$ASSET_DIR/firecracker" --version | head -1
"$ASSET_DIR/jailer" --version | head -1

note "host is ready. next:"
note "  recomp coordinator setup --owner <owner> --repository <repo> \\"
note "      --app-id <id> --installation-id <id> --trusted-actor-id <bot-id> \\"
note "      --image ghcr.io/<you>/<game>-toolchain@sha256:<64hex> \\"
note "      --project-root <checkout> --target <your target copy> \\"
note "      --firecracker $ASSET_DIR/firecracker --jailer $ASSET_DIR/jailer \\"
note "      --kernel $ASSET_DIR/vmlinux-6.1.102 \\"
note "      --rootfs <recomp toolchain rootfs output> \\"
note "      --jail-root ~/.local/share/recomp/jails/<repo> --poll-interval 60"
note "  recomp coordinator doctor --owner <owner> --repository <repo>   # must be all ok"
note "  recomp coordinator install-service --owner <owner> --repository <repo> --protect-home read-only"
note "then run the printed sudo install/systemctl commands (the unit carries the"
note "jailer's capabilities; the service needs no sudo at runtime)."
